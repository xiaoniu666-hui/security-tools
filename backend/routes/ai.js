function levenshteinDistance(a, b) {
  const matrix = Array.from({ length: a.length + 1 }, () => Array(b.length + 1).fill(0))
  
  for (let i = 0; i <= a.length; i++) matrix[i][0] = i
  for (let j = 0; j <= b.length; j++) matrix[0][j] = j
  
  for (let i = 1; i <= a.length; i++) {
    for (let j = 1; j <= b.length; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1
      matrix[i][j] = Math.min(
        matrix[i - 1][j] + 1,
        matrix[i][j - 1] + 1,
        matrix[i - 1][j - 1] + cost
      )
    }
  }
  
  return matrix[a.length][b.length]
}

function jaccardSimilarity(a, b) {
  const setA = new Set(a.split(''))
  const setB = new Set(b.split(''))
  const intersection = [...setA].filter(x => setB.has(x)).length
  const union = setA.size + setB.size - intersection
  return union === 0 ? 0 : intersection / union
}

function getSynonyms(word) {
  for (const [key, values] of Object.entries(synonyms)) {
    if (values.includes(word)) {
      return values
    }
  }
  return [word]
}

function extractKeywords(text) {
  const keywords = []
  const lowerText = text.toLowerCase()
  
  for (const [keyword] of Object.entries(knowledgeBase)) {
    const lowerKeyword = keyword.toLowerCase()
    if (lowerText.includes(lowerKeyword)) {
      keywords.push(keyword)
    }
  }
  
  for (const [synonymKey, synonymValues] of Object.entries(synonyms)) {
    for (const synonym of synonymValues) {
      if (lowerText.includes(synonym.toLowerCase())) {
        keywords.push(synonymKey)
      }
    }
  }
  
  return [...new Set(keywords)]
}

function findBestMatch(question, threshold = 0.3) {
  const lowerQuestion = question.toLowerCase()
  let bestMatch = null
  let highestScore = 0
  
  for (const [keyword, answer] of Object.entries(knowledgeBase)) {
    const lowerKeyword = keyword.toLowerCase()
    
    let score = 0
    
    if (lowerQuestion.includes(lowerKeyword)) {
      score += 1.0
    }
    
    const keywordsInQuestion = extractKeywords(question)
    if (keywordsInQuestion.includes(keyword)) {
      score += 0.5
    }
    
    const jaccard = jaccardSimilarity(lowerQuestion, lowerKeyword)
    score += jaccard * 0.5
    
    const levDist = levenshteinDistance(lowerQuestion, lowerKeyword)
    const maxLen = Math.max(lowerQuestion.length, lowerKeyword.length)
    const levScore = 1 - (levDist / maxLen)
    score += levScore * 0.3
    
    const wordsInQuestion = lowerQuestion.split(/\s+/)
    const wordsInKeyword = lowerKeyword.split(/\s+/)
    let wordMatchCount = 0
    for (const word of wordsInKeyword) {
      if (wordsInQuestion.includes(word)) {
        wordMatchCount++
      }
    }
    if (wordsInKeyword.length > 0) {
      score += (wordMatchCount / wordsInKeyword.length) * 0.2
    }
    
    if (score > highestScore && score >= threshold) {
      highestScore = score
      bestMatch = { keyword, answer, score }
    }
  }
  
  return bestMatch
}

