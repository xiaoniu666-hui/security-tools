function generateAnswer(question, context) {
  // 先尝试精确匹配关键词
  const lowerQuestion = question.toLowerCase()
  let bestMatch = null
  
  for (const [keyword, answer] of Object.entries(knowledgeBase)) {
    const lowerKeyword = keyword.toLowerCase()
    if (lowerQuestion.includes(lowerKeyword)) {
      // 优先匹配更长的关键词
      if (!bestMatch || keyword.length > bestMatch.keyword.length) {
        bestMatch = { keyword, answer }
      }
    }
  }
  
  // 如果找到精确匹配，直接返回
  if (bestMatch) {
    return bestMatch.answer + '\n\n' + followUps[Math.floor(Math.random() * followUps.length)]
  }
  
  // 打招呼
  if (lowerQuestion.includes('你好') || lowerQuestion.includes('您好') || lowerQuestion.includes('hi') || lowerQuestion.includes('hello') || lowerQuestion.includes('嗨')) {
    return greetings[Math.floor(Math.random() * greetings.length)]
  }
  
  // 询问使用方法，但没有具体关键词
  if (lowerQuestion.includes('如何使用') || lowerQuestion.includes('怎么用') || lowerQuestion.includes('使用方法')) {
    const features = Object.keys(knowledgeBase).slice(0, 10).join('、')
    return `我可以帮助您了解以下功能的使用方法：${features}等。请问您想了解哪个具体功能的使用方法？`
  }
  
  // 询问帮助
  if (lowerQuestion.includes('帮助') || lowerQuestion.includes('怎么') || lowerQuestion.includes('教程')) {
    const features = Object.keys(knowledgeBase).slice(0, 10).join('、')
    return `我可以帮助您了解以下功能和安全知识：${features}等。请问您想了解哪个的使用方法？`
  }
  
  // 询问功能/工具
  if (lowerQuestion.includes('功能') || lowerQuestion.includes('工具')) {
    const tools = ['IP查询', '域名查询', 'XSS测试', 'SQL注入', '漏洞扫描', '数据清洗', '爬虫', '安全监控']
    return `当前系统支持的工具有：${tools.join('、')}等。请问您想了解哪个工具？`
  }
  
  // 询问安全相关
  if (lowerQuestion.includes('漏洞') || lowerQuestion.includes('安全')) {
    const topics = ['XSS攻击', 'SQL注入', 'CSRF攻击', 'DDoS攻击', '安全最佳实践', '渗透测试']
    return `我可以为您讲解各种安全知识，包括：${topics.join('、')}等。请问您想了解哪个？`
  }
  
  if (context) {
    return `根据之前的对话，您问的是关于"${question}"。我可以帮助您了解网络安全相关的各种工具和知识。目前支持的主题包括工具使用、攻击类型、安全实践和安全技术等方面。`
  }
  
  return `我不太理解您的问题。我可以帮助您了解网络安全工具集的各种功能和网络安全知识。请问您想了解哪个方面？`
}

