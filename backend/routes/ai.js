router.post('/ask', async (req, res) => {
  const { question, sessionId, userId } = req.body
  
  if (!question) {
    return res.status(400).json({ error: '请输入问题' })
  }
  
  try {
    let context = ''
    let history = []
    
    if (sessionId && sessions[sessionId]) {
      history = sessions[sessionId].history || []
      context = history.slice(-3).map(h => `${h.question} -> ${h.answer}`).join('\n')
    }
    
    const answer = generateAnswer(question, context)
    
    if (!sessions[sessionId]) {
      sessions[sessionId] = { userId, history: [] }
    }
    
    sessions[sessionId].history.push({ question, answer })
    
    try {
      await insert('ai_conversations', {
        user_id: userId || 0,
        session_id: sessionId,
        question,
        answer,
        context
      })
    } catch (dbError) {
      console.log('Failed to save conversation:', dbError.message)
    }
    
    res.json({
      success: true,
      answer,
      sessionId,
      context: sessions[sessionId].history.length > 1
    })
  } catch (error) {
    res.status(500).json({ error: '回答失败', details: error.message })
  }
})

